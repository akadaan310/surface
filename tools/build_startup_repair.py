#!/usr/bin/env python3
"""Repackage the verified native core with the tested Java startup repair."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--toolchain', required=True, type=Path)
    parser.add_argument('--keystore', required=True, type=Path)
    args = parser.parse_args()
    tc = args.toolchain.resolve()
    key = args.keystore.resolve()
    if not key.is_file():
        raise SystemExit('Restore the already-backed-up recovery keystore; no key is generated by this builder')
    bt = tc / 'android-16'
    platform = tc / 'android-36/android.jar'
    out = ROOT / 'build/startup-repair'
    classes = out / 'classes'
    classes.mkdir(parents=True, exist_ok=True)
    evidence = ROOT / 'evidence/startup-package'
    evidence.mkdir(parents=True, exist_ok=True)
    records = []

    def run(label, argv, timeout=60):
        argv = [str(value) for value in argv]
        result = subprocess.run(argv, cwd=ROOT, text=True, capture_output=True, timeout=timeout)
        log = evidence / (label + '.log')
        log.write_text(result.stdout + result.stderr)
        records.append({'label': label, 'argv': argv, 'timeout_seconds': timeout, 'exit_code': result.returncode, 'log': str(log.relative_to(ROOT))})
        if result.returncode:
            raise RuntimeError(label + ' failed; see ' + str(log))
        return result.stdout + result.stderr

    origin = json.loads((ROOT / 'evidence/startup-native-origin.json').read_text())
    native = ROOT / origin['native_library_path']
    if sha(native) != origin['native_library_sha256']:
        raise SystemExit('Native library origin digest mismatch')
    green = json.loads((ROOT / 'evidence/startup-jni-green.json').read_text())
    if not green['passed'] or sha(ROOT / 'android/SurfaceActivity.java') != green['actual_activity']['sha256']:
        raise SystemExit('The actual Java source has no matching passing JNI startup witness')
    run('compile-java', ['java', '-m', 'jdk.compiler/com.sun.tools.javac.Main', '-source', '8', '-target', '8', '-classpath', platform, '-d', classes, ROOT / 'android/SurfaceActivity.java'])
    activity = classes / 'org/surface/nativeink/SurfaceActivity.class'
    if sha(activity) != green['compiled_activity_sha256']:
        raise SystemExit('Packaged Activity class differs from the class in the passing startup regression')
    run('dex', ['java', '-cp', bt / 'lib/d8.jar', 'com.android.tools.r8.D8', '--min-api', '29', '--lib', platform, '--output', out, activity])
    unsigned = out / 'unsigned.apk'
    aligned = out / 'aligned.apk'
    apk = out / 'Surface-Recovery-0.1.1-arm64.apk'
    run('resources', [bt / 'aapt2', 'link', '-I', platform, '--manifest', ROOT / 'android/AndroidManifest.recovery.xml', '--min-sdk-version', '29', '--target-sdk-version', '36', '-A', ROOT / 'data', '-o', unsigned])
    with zipfile.ZipFile(unsigned, 'a', zipfile.ZIP_DEFLATED, 6) as archive:
        archive.write(native, 'lib/arm64-v8a/libsurface.so')
        archive.write(out / 'classes.dex', 'classes.dex')
    run('align', [bt / 'zipalign', '-f', '-p', '4', unsigned, aligned])
    run('sign', [bt / 'apksigner', 'sign', '--ks', key, '--ks-key-alias', 'surface-development', '--ks-pass', 'pass:android', '--key-pass', 'pass:android', '--out', apk, aligned])
    signature = run('verify-signature', [bt / 'apksigner', 'verify', '--verbose', '--print-certs', apk])
    run('verify-alignment', [bt / 'zipalign', '-c', '-v', '4', apk])
    manifest = run('inspect-manifest', [bt / 'aapt2', 'dump', 'badging', apk])
    elf = run('inspect-native', ['readelf', '--wide', '--file-header', '--program-headers', '--dynamic', '--dyn-syms', native])
    expected_cert = json.loads((ROOT / 'evidence/signing-recovery.json').read_text())['new_certificate_sha256']
    needed = [line for line in elf.splitlines() if '(NEEDED)' in line]
    allowed = ('libandroid.so', 'liblog.so', 'libaaudio.so', 'libm.so', 'libdl.so', 'libc.so')
    checks = {
        'recovery_application_id': "name='org.surface.nativeink.recovery'" in manifest,
        'fully_qualified_existing_activity': "launchable-activity: name='org.surface.nativeink.SurfaceActivity'" in manifest,
        'arm64': "native-code: 'arm64-v8a'" in manifest and 'AArch64' in elf,
        'minimum_api29': "minSdkVersion:'29'" in manifest or "sdkVersion:'29'" in manifest,
        'no_requested_permissions': 'uses-permission:' not in manifest,
        'version_code2': "versionCode='2'" in manifest,
        'pinned_recovery_signing_certificate': expected_cert in signature,
        'all_load_segments_16k_aligned': all(line.rstrip().endswith('0x4000') for line in elf.splitlines() if line.strip().startswith('LOAD')),
        'platform_only_dynamic_dependencies': bool(needed) and all(any('[' + name + ']' in line for name in allowed) for line in needed),
        'jni_and_native_entry_points': all(name in elf for name in ('ANativeActivity_onCreate', 'Java_org_surface_nativeink_SurfaceActivity_nativeDimensions', 'Java_org_surface_nativeink_SurfaceActivity_nativeOpen')),
        'compiled_class_matches_passing_regression': sha(activity) == green['compiled_activity_sha256'],
    }
    with zipfile.ZipFile(apk) as archive:
        checks['archive_crc'] = archive.testzip() is None
        checks['native_payload_unchanged'] = hashlib.sha256(archive.read('lib/arm64-v8a/libsurface.so')).hexdigest() == origin['native_library_sha256']
        checks['assets_match_recovered_sources'] = all(archive.read('assets/' + str(p.relative_to(ROOT / 'data'))) == p.read_bytes() for p in (ROOT / 'data').rglob('*') if p.is_file())
    receipt = {
        'schema': 'surface-startup-repair-package-v1',
        'passed': all(checks.values()),
        'artifact': str(apk.relative_to(ROOT)), 'bytes': apk.stat().st_size, 'sha256': sha(apk),
        'application_id': 'org.surface.nativeink.recovery', 'launcher_name': 'Surface Recovery', 'version': '0.1.1',
        'activity_class': 'org.surface.nativeink.SurfaceActivity', 'native_library_sha256': sha(native),
        'certificate_sha256': expected_cert, 'checks': checks, 'commands': records,
        'change': 'Static System.loadLibrary("surface") before Java JNI calls; side-by-side application identity because original private key was unavailable',
        'android_device_execution': 'NOT_RUN; host JVM JNI regression and package verification only',
        'device_crash_causality': 'Concrete matching startup defect reproduced on actual Java class; original phone log unavailable',
    }
    (ROOT / 'evidence/startup-repair-build.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps({key: receipt[key] for key in ('passed', 'artifact', 'bytes', 'sha256', 'checks', 'android_device_execution')}, indent=2))
    if not receipt['passed']:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
